import type { Branding, BrandingRefs } from '../../../types'

/** CSS custom property holding the brand font stack (defined in the generated global theme file). */
export const FONT_CSS_VAR = '--app-font-family'

/** Text rendered in place of the logo when the user did not provide one. */
export const LOGO_PLACEHOLDER_TEXT = 'LOGO'

/** Accepted logo MIME types and the asset extension used for each. */
export const LOGO_MIME_TYPES: Record<string, string> = {
  'image/png': 'png',
  'image/svg+xml': 'svg',
  'image/jpeg': 'jpg',
}

