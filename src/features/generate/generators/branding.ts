export const FONT_SUGGESTIONS: string[] = [...GOOGLE_FONTS, ...WEB_SAFE_FONTS]

const SERIF_FONTS = new Set(
  ['Merriweather', 'Lora', 'Playfair Display', 'Georgia', 'Times New Roman', 'Garamond', 'Cambria'].map((f) =>
    f.toLowerCase(),
  ),
)

const SYSTEM_STACK = "system-ui, -apple-system, 'Segoe UI', Roboto"

/**
 * Normalise a user/document supplied font family so it can be safely interpolated
 * into CSS, TS and HTML (letters, digits, spaces and hyphens only).
 */
export function sanitizeFontFamily(input: string | undefined | null): string | undefined {
  const cleaned = (input ?? '')
    .replace(/[^A-Za-z0-9 -]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 64)
    .trim()
  return cleaned || undefined
}

/** Full CSS font stack for a family, e.g. `'Inter', system-ui, …, sans-serif`. */
export function fontStack(fontFamily?: string): string {
  const family = sanitizeFontFamily(fontFamily)
  if (!family) return `${SYSTEM_STACK}, sans-serif`
  const generic = SERIF_FONTS.has(family.toLowerCase()) ? 'serif' : 'sans-serif'
  return `'${family}', ${SYSTEM_STACK}, ${generic}`
}

/** `font-family` value used by generated screens: the theme variable with the brand stack as fallback. */
export function fontDeclaration(refs: BrandingRefs = {}): string {
  return `var(${FONT_CSS_VAR}, ${fontStack(refs.fontFamily)})`
}

/** Asset extension for a logo MIME type (undefined when unsupported). */
export function logoExtension(mimeType: string): string | undefined {
  return LOGO_MIME_TYPES[mimeType.toLowerCase()]
}

/** Prompt-safe references for the confirmed branding (drops binary data, sanitises the font). */
export function toBrandingRefs(branding: Branding = {}): BrandingRefs {
  const refs: BrandingRefs = {}
  const fontFamily = sanitizeFontFamily(branding.fontFamily)
  if (fontFamily) refs.fontFamily = fontFamily
  const ext = branding.logo ? logoExtension(branding.logo.mimeType) : undefined
  if (ext) refs.logoAsset = `logo.${ext}`
  return refs
}

export function sameBrandingRefs(a: BrandingRefs = {}, b: BrandingRefs = {}): boolean {
  return a.fontFamily === b.fontFamily && a.logoAsset === b.logoAsset
}

/** Google Fonts stylesheet URL for known Google families (null for web-safe/unknown fonts). */
export function googleFontsHref(fontFamily?: string): string | null {
  const family = sanitizeFontFamily(fontFamily)
  const match = family && GOOGLE_FONTS.find((f) => f.toLowerCase() === family.toLowerCase())
  if (!match) return null
  return `https://fonts.googleapis.com/css2?family=${match.replace(/ /g, '+')}:wght@400;500;600;700&display=swap`
}

/** Global theme stylesheet (CSS, also valid SCSS) defining the brand font variable. */
export function buildThemeCss(refs: BrandingRefs = {}): string {
  return `/* Global theme generated by UI Coding Agent. Change the brand font here. */
:root {
  ${FONT_CSS_VAR}: ${fontStack(refs.fontFamily)};
  color-scheme: light;
}

*,
*::before,
*::after {
  box-sizing: border-box;
}

body {
  margin: 0;
  font-family: var(${FONT_CSS_VAR});
  color: #0f172a;
  background: #f8fafc;
}
`
}

/** Decode a `data:` URL into raw bytes (base64 or percent-encoded). */
export function dataUrlToBytes(dataUrl: string): Uint8Array {
  const m = dataUrl.match(/^data:([^;,]*)((?:;[^;,]*)*),(.*)$/s)
  if (!m) throw new Error('Invalid data URL')
  if (/;base64/i.test(m[2])) {
    const binary = atob(m[3])
    return Uint8Array.from(binary, (c) => c.charCodeAt(0))
  }
  return new TextEncoder().encode(decodeURIComponent(m[3]))
}
