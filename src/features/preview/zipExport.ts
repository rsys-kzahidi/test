import JSZip from 'jszip'
import type { Branding, BrandingRefs, GenerationResult, Screen } from '../../types'
import { toKebabCase } from '../../utils/strings'
import { sanitizePath } from '../generate/fileFormat'
import { buildThemeCss, dataUrlToBytes, FONT_CSS_VAR, toBrandingRefs } from '../generate/generators/branding'

export const ZIP_ROOT = 'ui-coding-agent-output'

/** Folder name for a screen, de-duplicated across screens. */
function folderNames(results: GenerationResult[]): Map<string, string> {
  const used = new Map<string, number>()
  const out = new Map<string, string>()
  for (const r of results) {
    const base = toKebabCase(r.screenName)
    const count = used.get(base) ?? 0
    used.set(base, count + 1)
    out.set(r.screenId, count === 0 ? base : `${base}-${count + 1}`)
  }
  return out
}

function brandingNotes(refs: BrandingRefs): string {
  if (!refs.fontFamily && !refs.logoAsset) return ''
  const lines = ['## Branding', '']
  if (refs.fontFamily) {
    lines.push(
      `- Font family \`${refs.fontFamily}\`: include \`theme.css\` globally (it defines the \`${FONT_CSS_VAR}\` variable used by every screen).`,
    )
  }
  if (refs.logoAsset) {
    lines.push(
      `- Logo \`assets/${refs.logoAsset}\`: copy it to \`src/assets/\` (React screens import \`../../assets/${refs.logoAsset}\` from \`src/screens/<Screen>/\`; Angular screens use \`assets/${refs.logoAsset}\`).`,
    )
  }
  return `\n${lines.join('\n')}\n`
}

function readme(results: GenerationResult[], folders: Map<string, string>, refs: BrandingRefs = {}): string {
  const rows = results
    .map((r) => `| ${r.screenName} | ${r.framework} | \`${folders.get(r.screenId)}/\` | ${r.files.length} |`)
    .join('\n')
  const frameworks = new Set(results.map((r) => r.framework))
  const notes: string[] = []
  if (frameworks.has('react')) {
    notes.push(`### React
- Copy a screen folder into your React + TypeScript project (e.g. \`src/screens/\`).
- Requires \`"resolveJsonModule": true\` in tsconfig (enabled by default in Vite templates).
- Each \`use<Screen>Data.ts\` exports an endpoint constant and a \`USE_MOCK\` flag — flip it to call the real API.`)
  }
  if (frameworks.has('angular')) {
    notes.push(`### Angular
- Copy a screen folder into \`src/app/\` of an Angular 17+ project; components are standalone.
- Add \`provideHttpClient()\` to your \`app.config.ts\` providers and \`"resolveJsonModule": true\` to tsconfig.
- Each \`<screen>.service.ts\` has a \`useMock\` flag — set it to \`false\` to call the real endpoint.`)
  }
  return `# Generated UI screens

Generated by **UI Coding Agent**. Each folder contains one screen: the UI component,
its styles, a dummy JSON API response and an API layer that resolves that JSON with
simulated latency so it can later be swapped for a real backend.

| Screen | Framework | Folder | Files |
| --- | --- | --- | --- |
${rows}

${notes.join('\n\n')}
${brandingNotes(refs)}`
}

/**
 * Build a JSZip archive with one folder per screen:
 *   ui-coding-agent-output/<screen-name>/<files…>, plus README.md and manifest.json.
 * When branding is provided, `theme.css` and the logo under `assets/` are added too.
 * Only successfully generated screens are included.
 */
export function buildZip(results: GenerationResult[], screens: Screen[] = [], branding: Branding = {}): JSZip {
  const done = results.filter((r) => r.status === 'done' && r.files.length > 0)
  const zip = new JSZip()
  const root = zip.folder(ZIP_ROOT)!
  const folders = folderNames(done)

  for (const result of done) {
    const folder = root.folder(folders.get(result.screenId)!)!
    for (const file of result.files) {
      const path = sanitizePath(file.path)
      if (path) folder.file(path, file.content)
    }
  }

  const manifest = {
    generator: 'ui-coding-agent',
    generatedAt: new Date().toISOString(),
    screens: done.map((r) => {
      const screen = screens.find((s) => s.id === r.screenId)
      return {
        name: r.screenName,
        folder: folders.get(r.screenId),
        framework: r.framework,
        provider: r.provider,
        model: r.model,
        description: screen?.description,
        files: r.files.map((f) => ({ path: sanitizePath(f.path), kind: f.kind })),
      }
    }),
  }
  root.file('manifest.json', `${JSON.stringify(manifest, null, 2)}\n`)
  const refs = toBrandingRefs(branding)
  if (refs.fontFamily || refs.logoAsset) root.file('theme.css', buildThemeCss(refs))
  if (refs.logoAsset && branding.logo) root.file(`assets/${refs.logoAsset}`, dataUrlToBytes(branding.logo.dataUrl))
  root.file('README.md', readme(done, folders, refs))
  return zip
}

/** Generate the ZIP as a Blob and trigger a browser download. */
export async function downloadZip(
  results: GenerationResult[],
  screens: Screen[] = [],
  fileName = `${ZIP_ROOT}.zip`,
  branding: Branding = {},
): Promise<void> {
  const { saveAs } = await import('file-saver')
  const blob = await buildZip(results, screens, branding).generateAsync({ type: 'blob', compression: 'DEFLATE' })
  saveAs(blob, fileName)
}
